'use strict';
const fs = require('fs');
const path = require('path');
const { readSMF } = require('./midi.js');

const MUTOPIA = 'Mutopia Project (mutopiaproject.org)';
// speed: tempo factor (LilyPond writes 60 BPM when the score has no tempo mark)
// end: hard cut (s); maxEnd: cut at the most natural phrase gap shortly before this time (s)
const SONGS = [
  // first = the default demo (▶ DEMO): Appassionata with a tour of the factory presets, about one every 4 s
  { id: 'appassionata', file: 'appassionata3.mid', title: 'Sonata "Appassionata" Op. 57 — III. Allegro ma non troppo, Presto',
    short: 'Appassionata (III)', composer: 'L. van Beethoven', maxEnd: 140,
    url: 'https://www.mutopiaproject.org/ftp/BeethovenLv/O57/LVB_Sonate_57_3/LVB_Sonate_57_3.mid' },
  { id: 'toccata', file: 'ToccataFugue.mid', title: 'Toccata in D minor, BWV 565', short: 'Toccata in D minor', composer: 'J. S. Bach', end: 118.3,
    url: 'https://www.mutopiaproject.org/cgibin/piece-info.cgi?id=1780' },
  // more virtuoso Beethoven piano works (first ~2-2.5 minutes, cut at a phrase)
  { id: 'moonlight', file: 'moonlight3.mid', title: 'Sonata "Moonlight" Op. 27 No. 2 — III. Presto agitato',
    short: 'Moonlight Sonata (III)', composer: 'L. van Beethoven', speed: 2.8, maxEnd: 150,
    license: 'CC BY-SA 2.5', source: 'Mutopia Project, typeset by Stewart Holmes',
    url: 'https://www.mutopiaproject.org/cgibin/piece-info.cgi?id=276' },
  { id: 'rondo', file: 'rondo129.mid', title: 'Rondo a capriccio Op. 129 "Rage over a Lost Penny"',
    short: 'Rage over a Lost Penny', composer: 'L. van Beethoven', maxEnd: 135,
    url: 'https://www.mutopiaproject.org/ftp/BeethovenLv/O129/beethoven_rondo_op129/beethoven_rondo_op129.mid' },
  { id: 'symphony5', file: 'symphony5.mid', title: 'Symphony No. 5 Op. 67 — I. Allegro con brio (piano)',
    short: 'Symphony No. 5 (piano)', composer: 'L. van Beethoven', maxEnd: 125,
    url: 'https://www.mutopiaproject.org/ftp/BeethovenLv/O67/beethoven_fifth_op67/beethoven_fifth_op67.mid' },
  { id: 'pathetique', file: 'pathetique1.mid', title: 'Sonata "Pathétique" Op. 13 — I. Grave, Allegro di molto e con brio',
    short: 'Pathétique (I)', composer: 'L. van Beethoven', maxEnd: 140,
    url: 'https://www.mutopiaproject.org/ftp/BeethovenLv/O13/pathetique-1/pathetique-1.mid' },
  { id: 'tempest', file: 'tempest1.mid', title: 'Sonata "The Tempest" Op. 31 No. 2 — I. Largo, Allegro',
    short: 'The Tempest (I)', composer: 'L. van Beethoven', maxEnd: 140,
    url: 'https://www.mutopiaproject.org/ftp/BeethovenLv/O31/LVB_Sonate_31no2_1/LVB_Sonate_31no2_1.mid' },
  { id: 'op111', file: 'op111_1.mid', title: 'Sonata No. 32 Op. 111 — I. Maestoso, Allegro con brio ed appassionato',
    short: 'Sonata Op. 111 (I)', composer: 'L. van Beethoven', maxEnd: 150,
    url: 'https://www.mutopiaproject.org/ftp/BeethovenLv/O111/lvb_sonate_111_1/lvb_sonate_111_1.mid' },
];

const out = [];
for (const s of SONGS) {
  const m = readSMF(fs.readFileSync(path.join(__dirname, 'demo', s.file)));
  const speed = s.speed || 1;
  let notes = m.notes.filter(n => n.ch !== 9).map(n => ({ t: n.t / speed, d: n.d / speed, note: n.note, vel: n.vel }));
  let cut = s.end || Infinity;
  if (s.maxEnd) {
    const on = [...new Set(notes.map(n => +n.t.toFixed(4)))].sort((a, b) => a - b);
    let best = s.maxEnd, gap = -1;
    for (let i = 1; i < on.length; i++) if (on[i] > s.maxEnd - 20 && on[i] <= s.maxEnd && on[i] - on[i - 1] >= gap) { gap = on[i] - on[i - 1]; best = on[i]; }
    cut = best;
  }
  notes = notes.filter(n => n.t < cut - 1e-6);
  const flat = [];
  for (const n of notes) flat.push(+n.t.toFixed(4), +Math.max(0.03, n.d).toFixed(4), n.note, +(n.vel / 127).toFixed(3));
  const duration = Math.max(...notes.map(n => n.t + n.d));
  out.push({ id: s.id, title: s.title, short: s.short || s.title, composer: s.composer, source: s.source || MUTOPIA,
    license: s.license || 'Public Domain', url: s.url, duration: +duration.toFixed(3), notes: flat });
  console.log(`${s.id.padEnd(12)} ${notes.length} notes, ${duration.toFixed(1)} s${speed !== 1 ? ` (speed x${speed})` : ''}${s.maxEnd ? `, cut at ${cut.toFixed(2)} s` : ''}`);
}
const js = '// GENERATED by tools/make_demo.js from the MIDI files in tools/demo/ — do not edit.\n' +
  '// Note data from the Mutopia Project: public domain, except the "Moonlight" Sonata III (CC BY-SA 2.5, typeset by\n' +
  '// Stewart Holmes). This data is not covered by the GPL licence of the program; see tools/demo/SOURCE.md.\n' +
  'var WS_DEMO_SONGS = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'web', 'js', 'demo_data.js'), js);
console.log(`web/js/demo_data.js: ${(js.length / 1024).toFixed(1)} KB`);
