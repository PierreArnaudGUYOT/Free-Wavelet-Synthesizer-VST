// Converts the demo song (Beethoven's Appassionata III, a public-domain MIDI file in tools/demo/) into web/js/demo_data.js.
// Usage: node tools/make_demo.js
'use strict';
const fs = require('fs');
const path = require('path');
const { readSMF } = require('./midi.js');

const MUTOPIA = 'Mutopia Project (mutopiaproject.org)';
// speed: tempo factor (LilyPond writes 60 BPM when the score has no tempo mark)
// end: hard cut (s); maxEnd: cut at the most natural phrase gap shortly before this time (s)
// start: the demo begins at the first note at or after this time (s), the opening bars are cut; the song keeps that
//        time as `origin`. Version 1.0.10: the preset tour of web/js/demo.js changes preset every 8 beats from the start (`phrase`, `beat`: the tempo fitted on the onsets,
//        134 per minute), at the start of the theme's phrase; it was a change of chord near every 4 s of the whole piece
// The final version has one song only (the owner removed the others and the song menu); web/js/demo_data.js keeps the array form
// (WS_DEMO_SONGS[0]) because tools/supermod/gain.js and loud_filter.js read song 0 for their loudness passage.
const SONGS = [
  // the demo (▶ DEMO): Appassionata with a tour of the factory presets, about one every 4 s
  { id: 'appassionata', file: 'appassionata3.mid', title: 'Sonata "Appassionata" Op. 57 — III. Allegro ma non troppo, Presto',
    short: 'Appassionata (III)', composer: 'L. van Beethoven', maxEnd: 140, start: 17.0,   // version 1.0.10: from the low F that starts the theme of the right hand (the opening line and chords are cut); before: 7.8, the phrase after the opening chords
    url: 'https://www.mutopiaproject.org/ftp/BeethovenLv/O57/LVB_Sonate_57_3/LVB_Sonate_57_3.mid' },
];

const out = [];
for (const s of SONGS) {
  const m = readSMF(fs.readFileSync(path.join(__dirname, 'demo', s.file)));
  const speed = s.speed || 1;
  let notes = m.notes.filter(n => n.ch !== 9).map(n => ({ t: n.t / speed, d: n.d / speed, note: n.note, vel: n.vel }));
  let cut = s.end || Infinity;
  if (s.maxEnd) {
    const on = [...new Set(notes.map(n => +n.t.toFixed(4)))].sort((a, b) => a - b);
    let best = s.maxEnd, gap = -1;
    for (let i = 1; i < on.length; i++) if (on[i] > s.maxEnd - 20 && on[i] <= s.maxEnd && on[i] - on[i - 1] >= gap) { gap = on[i] - on[i - 1]; best = on[i]; }
    cut = best;
  }
  notes = notes.filter(n => n.t < cut - 1e-6);
  let origin = 0;
  if (s.start) {
    origin = Math.min(...notes.filter(n => n.t >= s.start - 1e-6).map(n => n.t));
    notes = notes.filter(n => n.t >= origin - 1e-6).map(n => Object.assign(n, { t: n.t - origin }));
  }
  const flat = [];
  for (const n of notes) flat.push(+n.t.toFixed(4), +Math.max(0.03, n.d).toFixed(4), n.note, +(n.vel / 127).toFixed(3));
  const duration = Math.max(...notes.map(n => n.t + n.d));
  // version 1.0.10: the beat, fitted on the onsets (every note starts on a sixteenth of the grid: n = round(t / b), least squares), and the phrase = 8 beats
  let sixteenth = 0.112;
  { const on = [...new Set(notes.map(n => +n.t.toFixed(4)))]; for (let it = 0; it < 8; it++) { let sn = 0, st = 0; for (const t of on) { const k = Math.round(t / sixteenth); sn += k * k; st += k * t; } sixteenth = st / sn; } }
  const beat = +(4 * sixteenth).toFixed(5), phrase = +(32 * sixteenth).toFixed(4);
  out.push(Object.assign({ id: s.id, title: s.title, short: s.short || s.title, composer: s.composer, source: s.source || MUTOPIA,
    license: s.license || 'Public Domain', url: s.url, duration: +duration.toFixed(3), beat, phrase }, origin ? { origin: +origin.toFixed(4) } : {},
    { notes: flat }));
  console.log(`${s.id.padEnd(12)} ${notes.length} notes, ${duration.toFixed(1)} s, beat ${beat} s, phrase ${phrase} s${speed !== 1 ? ` (speed x${speed})` : ''}${origin ? `, from ${origin.toFixed(2)} s` : ''}${s.maxEnd ? `, cut at ${cut.toFixed(2)} s` : ''}`);
}
const js = '// GENERATED by tools/make_demo.js from the MIDI file in tools/demo/ — do not edit.\n' +
  '// Note data from the Mutopia Project (Beethoven, Appassionata III): public domain. This data is not covered by the GPL licence\n' +
  '// of the program; see tools/demo/SOURCE.md.\n' +
  'var WS_DEMO_SONGS = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'web', 'js', 'demo_data.js'), js);
console.log(`web/js/demo_data.js: ${(js.length / 1024).toFixed(1)} KB`);
