// Version 1.0.15: the owner's own sounds, from the presets file his plug-in writes ("OKTOMULTIWAVE presets.txt", vst/src/bank.h). For every factory preset of the file:
//   "Adjusted: yes" -> the parameters whose value differs from the factory preset's (the file writes 6 decimals: a smaller difference is the rounding, not an edit);
//   "Deleted: yes"  -> the preset's built-in name.
// It writes tools/owner_presets.js (read by tools/spec.js: OWNER_EDITS, OWNER_DELETED). Run it against the factory list the owner's file was written by (web/js/spec.js of that version),
// BEFORE tools/spec.js applies the result (the comparison would otherwise find no difference).
//   node tools/owner_import.js "<path>/OKTOMULTIWAVE presets.txt" [--date 2026-10-23] [--out owner_presets2.js]
// (web update of 1.0.16: also his stars; --out writes another file, so that the edits of an earlier import stay)
'use strict';
const fs = require('fs');
const path = require('path');
const file = process.argv[2];
const arg = (k, d) => { const i = process.argv.indexOf('--' + k); return i >= 0 ? process.argv[i + 1] : d; };
if (!file || !fs.existsSync(file)) { console.error('usage: node tools/owner_import.js "<path>/OKTOMULTIWAVE presets.txt" [--date YYYY-MM-DD]'); process.exit(1); }
const SPEC = require(arg('spec', '') ? path.resolve(arg('spec', '')) : '../web/js/spec.js');   // (--spec: the web spec of the version that wrote the file, e.g. build/wt-main/web/js/spec.js)
const byName = new Map(SPEC.PRESETS.map(p => [p.name, p]));
// (version 1.0.17: --add-bank Bass: the sounds of that section of his user bank become factory presets of the section of the same name, "add" in the output)
const ADD_BANK = arg('add-bank', ''), add = [], hidden = new Set(SPEC.PARAMS.filter(p => p.perf || p.hidden).map(p => p.key));
let ubSec = '', ubCur = null;
const blocks = [], lists = {}; let cur = null, part = '', listSec = '';
for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
  if (line.startsWith('########')) { part = line.includes('YOUR PRESETS') ? '' : line.includes('FACTORY') ? 'F' : line.includes('LIST ORDER') ? 'L' : line.includes('USER BANK') ? 'U' : ''; cur = null; ubCur = null; continue; }
  if (part === 'U') {
    const h = line.match(/^== (.+) ==$/);
    if (h) { ubSec = h[1]; ubCur = null; continue; }
    if (!ADD_BANK || ubSec !== ADD_BANK) continue;
    if (line.startsWith('Preset: ')) { ubCur = { name: line.slice(8), cat: ADD_BANK, v: {} }; add.push(ubCur); }
    else if (ubCur && !line.startsWith('From: ') && !line.startsWith('Stars: ')) { const m = line.match(/^\s+(\w+): (\S+)/); if (m && !hidden.has(m[1])) ubCur.v[m[1]] = +m[2]; }
    continue;
  }
  if (part === 'L') {   // (web update of 1.0.16: his lists, as his browser shows them: what each holds, in its order; built-in names, the deleted ones marked)
    const h = line.match(/^== (.+) ==$/);
    if (h) { listSec = h[1]; lists[listSec] = []; } else if (listSec && line.trim() && !/\(deleted\)\s*$/.test(line)) lists[listSec].push(line.trim().replace(/^\d+\.\s*/, ''));
    continue;
  }
  if (part !== 'F') continue;
  if (line.startsWith('Preset: ')) { cur = { name: line.slice(8), params: {} }; blocks.push(cur); continue; }
  if (!cur) continue;
  if (line.startsWith('Factory: ')) cur.orig = line.slice(9);
  else if (line.startsWith('Adjusted: ')) cur.adj = line.slice(10).startsWith('yes');
  else if (line.startsWith('Deleted: ')) cur.del = line.slice(9).startsWith('yes');
  else if (line.startsWith('Stars: ')) cur.stars = parseInt(line.slice(7), 10) || 0;   // (web update of 1.0.16: his ratings, 1-10)
  else { const m = line.match(/^\s+(\w+): (\S+)/); if (m) cur.params[m[1]] = +m[2]; }
}
const adjusted = {}, deleted = [], unknown = [];
for (const b of blocks) {
  const f = byName.get(b.orig);
  if (!f) { unknown.push(b.orig); continue; }
  if (b.del) deleted.push(b.orig);
  if (!b.adj) continue;
  const edit = {};
  SPEC.PARAMS.forEach((p, i) => {
    if (p.perf || p.hidden) return;
    const nv = b.params[p.key] !== undefined ? b.params[p.key] : p.def;
    if (Math.abs(nv - f.values[i]) > 1e-6 * Math.max(1, Math.abs(nv))) edit[p.key] = nv;
  });
  if (Object.keys(edit).length) adjusted[b.orig] = edit;
}
// his ratings (web update of 1.0.16): the stars of every factory preset he rated, by built-in name
const stars = {};
for (const b of blocks) if (b.stars && byName.has(b.orig) && !b.del) stars[b.orig] = b.stars;
const out = path.join(__dirname, arg('out', 'owner_presets.js'));   // (web update of 1.0.16: --out owner_presets2.js, the second file; owner_presets.js keeps the edits of 1.0.15)
const body = '// Copyright (C) 2026 Pierre Arnaud GUYOT (OktoPierre)\n// SPDX-License-Identifier: GPL-3.0-or-later\n' +
  `// GENERATED by tools/owner_import.js from the owner's presets file of ${arg('date', 'his plug-in')}: the factory presets he adjusted with SAVE PRESET (only the parameters he changed),\n` +
  '// the ones he deleted in his browser and his stars. tools/spec.js applies them.\n' +
  "'use strict';\nmodule.exports = " + JSON.stringify(Object.assign({ adjusted, deleted, stars, lists }, ADD_BANK ? { add } : {}), null, 2) + ';\n';
fs.writeFileSync(out, body);
console.log(`${path.relative(process.cwd(), out)}: ${Object.keys(adjusted).length} adjusted presets with changes, ${deleted.length} deleted, ${Object.keys(stars).length} rated` +
  (ADD_BANK ? `, ${add.length} sounds of his ${ADD_BANK} bank to add (${add.map(a => a.name).join(', ')})` : '') + (unknown.length ? `; not in the factory list (ignored): ${unknown.join(', ')}` : ''));
