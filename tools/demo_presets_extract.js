// Version 1.0: the preset tour of the web demo is the one of the Wavelet Synthesizer's web app (beta 0.7.1, https://pierrearnaudguyot.github.io/Free-Wavelet-Synthesizer-VST/web/):
// the same piece (Beethoven's Appassionata, III), the same presets in the same order, at the same level. Those presets are not all in the factory list of this synthesizer (it keeps
// the 237 the owner rated 3 or more), so the tour carries its own copies: this tool reads them from the files of that web app (its demo.js for the order, its spec.js for the values)
// and writes tools/demo_presets.js: { name, v } in the parameters of that version (tools/spec.js converts them as it does the TOP Sounds: convertLegacy).
//   node tools/demo_presets_extract.js <folder with the files of the old web app: js/demo.js, js/spec.js>
'use strict';
const fs = require('fs');
const path = require('path');
const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/demo_presets_extract.js <folder with js/demo.js and js/spec.js of the Wavelet Synthesizer web app>'); process.exit(1); }
const demo = fs.readFileSync(path.join(dir, 'js', 'demo.js'), 'utf8');
const m = /const TOUR_APPASSIONATA = \[([\s\S]*?)\];/.exec(demo);
if (!m) throw new Error('TOUR_APPASSIONATA not found in demo.js');
const order = [...m[1].replace(/\/\/[^\n]*/g, '').matchAll(/'([^']+)'/g)].map(x => x[1]);
global.window = global;
// eslint-disable-next-line no-eval
eval(fs.readFileSync(path.join(dir, 'js', 'spec.js'), 'utf8') + ';global.OLD = WS_SPEC;');
const OLD = global.OLD, keys = OLD.PARAMS.map(p => p.key);
const byName = new Map(OLD.PRESETS.map(p => [p.name, p]));
const seen = new Set(), presets = [];
for (const name of order) {
  if (seen.has(name)) continue; seen.add(name);
  const p = byName.get(name);
  if (!p) throw new Error('preset not in the old spec: ' + name);
  const v = {}; keys.forEach((k, i) => { v[k] = p.values[i]; });
  presets.push({ name, v });
}
const text = ['// Copyright (C) 2026 Pierre Arnaud GUYOT (OktoPierre)', '// SPDX-License-Identifier: GPL-3.0-or-later',
  '// GENERATED by tools/demo_presets_extract.js from the web app of the Wavelet Synthesizer beta ' + OLD.APP.versionNum + ': the presets of its demo tour (' + presets.length + '), in the parameters of that version.',
  "'use strict';", 'module.exports = { order: ' + JSON.stringify(order) + ',\n presets: ' + JSON.stringify(presets) + ' };', ''].join('\n');
fs.writeFileSync(path.join(__dirname, 'demo_presets.js'), text);
console.log('tour of', order.length, 'entries,', presets.length, 'distinct presets, version', OLD.APP.versionNum, '->', 'tools/demo_presets.js', (text.length / 1024).toFixed(0) + ' KB');
