// Version 1.0.17: the New Waves sounds the owner kept. He rated the test bank (tools/new_waves_bank.js) in his plug-in; his words: "conserve tous ceux qui ont plus d'une
// étoile; copie-les dans les TOP Sounds s'ils ont plus de 6 étoiles, et répartis-les aussi dans les banques; les nouveaux sons qui ont une étoile ou moins, supprime-les".
// So a sound rated 2 or more (his file's 1-10 scale) becomes a factory preset, in the section of the sound it was made from (the factory preset of its "From:" name, else the
// list of his file that holds that name), and in TOP Sounds when rated 7 or more; tools/spec.js reads tools/presets_newwaves.js and orders every list by his stars.
//   node tools/newwaves_import.js "<path>/OKTOMULTIWAVE presets.txt"            writes tools/presets_newwaves.js
//   node tools/newwaves_import.js "<path>/OKTOMULTIWAVE presets.txt" --write    also his file: the New Waves bank keeps the sounds rated 2 or more (the others go), and the
//                                                                               factory copies get his stars and their places in his lists (TOP Sounds, their section), by stars
// Back his file up before --write; run --write with the plug-in that has these factory presets (an older one drops what it does not know when it saves).
'use strict';
const fs = require('fs');
const path = require('path');
const file = process.argv[2];
const arg = (k, d) => { const i = process.argv.indexOf('--' + k); return i >= 0 ? process.argv[i + 1] : d; };
if (!file || !fs.existsSync(file)) { console.error('usage: node tools/newwaves_import.js "<path>/OKTOMULTIWAVE presets.txt" [--write]'); process.exit(1); }
const KEEP = +arg('keep', 2), TOP = +arg('top', 7), BANK = 'New Waves';
const SPEC = require('../web/js/spec.js');
const hidden = new Set(SPEC.PARAMS.filter(p => p.perf || p.hidden).map(p => p.key));

// ---------------------------------------------------------------- his file
const text = fs.readFileSync(file, 'utf8'), crlf = /\r\n/.test(text), lines = text.split(/\r?\n/);
const bank = [], lists = {}, factoryStars = new Map();
{
  let part = '', sec = '', cur = null, fb = null;
  lines.forEach((line, i) => {
    if (line.startsWith('########')) {
      part = line.includes('YOUR PRESETS IN THE FACTORY LISTS') ? 'X' : line.includes('FACTORY') ? 'F' : line.includes('USER BANK') ? 'U' : line.includes('LIST ORDER') ? 'L' : '';
      sec = ''; cur = null; fb = null; return;
    }
    const h = line.match(/^== (.+) ==$/);
    if (h) { sec = h[1]; cur = null; if (part === 'L') lists[sec] = []; return; }
    if (part === 'F') {
      if (line.startsWith('Factory: ')) fb = line.slice(9);
      else if (line.startsWith('Stars: ') && fb) factoryStars.set(fb, parseInt(line.slice(7), 10) || 0);
      else if (line.startsWith('Preset: ')) fb = null;
    } else if (part === 'L' && sec) {
      const m = line.match(/^\d+\.\s+(.*?)(\s{3}\(.*\))?$/);
      if (m) lists[sec].push(m[1]);
    } else if (part === 'U' && sec === BANK) {
      if (line.startsWith('Preset: ')) { cur = { name: line.slice(8), stars: 0, params: {}, from: '', at: i }; bank.push(cur); }
      else if (cur && line.startsWith('Stars: ')) cur.stars = parseInt(line.slice(7), 10) || 0;
      else if (cur && line.startsWith('From: ')) cur.from = line.slice(6);
      else if (cur) { const m = line.match(/^ {2}(\w+): (\S+)/); if (m && !hidden.has(m[1])) cur.params[m[1]] = +m[2]; }
    }
  });
}
if (!bank.length) { console.error(`no "${BANK}" bank in ${file}`); process.exit(1); }
const factory = new Map(SPEC.PRESETS.map(p => [p.name, p]));
const catOf = (from) => {
  const f = factory.get(from);
  if (f && !f.newWave) return f.cat;
  for (const [sec, names] of Object.entries(lists)) if (sec !== 'TOP Sounds' && names.includes(from)) return sec;
  return 'Other';
};
const kept = bank.filter(p => p.stars >= KEEP).sort((a, b) => b.stars - a.stars || bank.indexOf(a) - bank.indexOf(b));
const out = kept.map(p => ({ name: p.name, from: p.from, cat: catOf(p.from), stars: p.stars, v: p.params }));

// ---------------------------------------------------------------- tools/presets_newwaves.js
const OUT = path.join(__dirname, 'presets_newwaves.js');
fs.writeFileSync(OUT, '// Copyright (C) 2026 Pierre Arnaud GUYOT (OktoPierre)\n// SPDX-License-Identifier: GPL-3.0-or-later\n' +
  `// GENERATED by tools/newwaves_import.js from the owner's presets file (${path.basename(file)}): the sounds of his New Waves test bank he rated ${KEEP} or more,\n` +
  `// each with the section of the sound it was made from and his stars (TOP Sounds from ${TOP}). tools/spec.js makes them factory presets.\n` +
  "'use strict';\nmodule.exports = [\n" + out.map(p => '  ' + JSON.stringify(p)).join(',\n') + '\n];\n');
const byCat = {}; for (const p of out) byCat[p.cat] = (byCat[p.cat] || 0) + 1;
console.log(`${path.relative(process.cwd(), OUT)}: ${out.length} of ${bank.length} sounds kept (rated ${KEEP}+), ${out.filter(p => p.stars >= TOP).length} for TOP Sounds; by section: ` +
  Object.entries(byCat).map(([c, n]) => `${c} ${n}`).join(', '));
if (!process.argv.includes('--write')) process.exit(0);

// ---------------------------------------------------------------- his file: the bank trimmed, the factory copies rated and placed
const keptNames = new Set(kept.map(p => p.name));
const res = [];
let part = '', sec = '', skip = false;
const factoryBlocks = out.flatMap(p => ['Preset: ' + p.name, 'Factory: ' + p.name, 'Adjusted: no', 'Stars: ' + p.stars, '']);
const starsOf = (n) => factoryStars.get(n) || (keptNames.has(n) ? kept.find(p => p.name === n).stars : 0);
// a list with the new names put in by stars (before the first one rated lower; TOP Sounds keeps its first sound first)
const placed = (sec, names) => {
  const add = out.filter(p => (sec === 'TOP Sounds' ? p.stars >= TOP : p.cat === sec) && !names.includes(p.name));
  const L = names.slice();
  for (const p of add) {
    let at = L.findIndex((n, k) => (sec !== 'TOP Sounds' || k > 0) && starsOf(n) < p.stars);
    if (at < 0) at = L.length;
    L.splice(at, 0, p.name);
  }
  return L;
};
for (let i = 0; i < lines.length; i++) {
  const line = lines[i];
  if (line.startsWith('########')) {
    if (part === 'F') { while (res.length && res[res.length - 1] === '') res.pop(); res.push('', ...factoryBlocks); }   // the factory copies at the end of the factory part
    part = line.includes('YOUR PRESETS IN THE FACTORY LISTS') ? 'X' : line.includes('FACTORY') ? 'F' : line.includes('USER BANK') ? 'U' : line.includes('LIST ORDER') ? 'L' : '';
    sec = ''; skip = false; res.push(line); continue;
  }
  const h = line.match(/^== (.+) ==$/);
  if (h) {
    sec = h[1]; skip = false; res.push(line);
    if (part === 'L') {   // the list, rewritten with the new names in it
      const names = placed(sec, lists[sec] || []), notes = new Map();
      let j = i + 1;
      for (; j < lines.length && !/^== .+ ==$/.test(lines[j]) && !lines[j].startsWith('########'); j++) {
        const m = lines[j].match(/^\d+\.\s+(.*?)(\s{3}\(.*\))?$/); if (m && m[2]) notes.set(m[1], m[2]);
      }
      names.forEach((n, k) => res.push(`${k + 1}. ${n}${notes.get(n) || ''}`));
      res.push('');
      i = j - 1;
    }
    continue;
  }
  if (part === 'U' && sec === BANK) {
    if (line.startsWith('Preset: ')) skip = !keptNames.has(line.slice(8));
    if (skip) continue;
  }
  res.push(line);
}
if (part === 'F') res.push('', ...factoryBlocks);
fs.writeFileSync(file, res.join(crlf ? '\r\n' : '\n'));
console.log(`${file}: the "${BANK}" bank keeps ${kept.length} sounds (${bank.length - kept.length} removed); ${out.length} factory copies rated and placed in the lists`);
