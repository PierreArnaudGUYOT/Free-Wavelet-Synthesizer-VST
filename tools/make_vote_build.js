// Builds the DEMO VOTE test version of the web app (the owner rates the presets of the demo; see tools/vote/vote.js): a copy of web/ plus the vote module, its style, the level trims of
// every factory preset (tools/demo_trim_all.js, from tools/demo_level.js --all --write-trim) and a "Vote on the demo presets" box in the welcome window.
//   node tools/make_vote_build.js [outdir]      default tools/out/vote_build
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..'), OUT = path.resolve(process.argv[2] || path.join(__dirname, 'out', 'vote_build'));
const rep = (s, a, b) => { if (s.split(a).length !== 2) throw new Error('not unique / missing: ' + a.slice(0, 70)); return s.replace(a, () => b); };

fs.rmSync(OUT, { recursive: true, force: true });
fs.cpSync(path.join(ROOT, 'web'), OUT, { recursive: true });
fs.copyFileSync(path.join(__dirname, 'vote', 'vote.js'), path.join(OUT, 'js', 'vote.js'));
fs.copyFileSync(path.join(__dirname, 'vote', 'vote.css'), path.join(OUT, 'css', 'vote.css'));
const trim = require('./demo_trim_all.js');
fs.writeFileSync(path.join(OUT, 'js', 'vote_data.js'), '// GENERATED by tools/make_vote_build.js from tools/demo_trim_all.js - do not edit.\nvar WS_VOTE_DATA = ' + JSON.stringify({ trim }) + ';\n');

let html = fs.readFileSync(path.join(OUT, 'index.html'), 'utf8'); const crlf = html.includes('\r\n'); html = html.replace(/\r\n/g, '\n');
html = rep(html, '<link rel="stylesheet" href="css/synth.css">', '<link rel="stylesheet" href="css/synth.css">\n<link rel="stylesheet" href="css/vote.css">');
html = rep(html, '<script src="js/app.js"></script>', '<script src="js/vote_data.js"></script>\n<script src="js/vote.js"></script>\n<script src="js/app.js"></script>');
html = rep(html, '    <div class="choices">\n', `    <div class="choices">
      <button id="w-vote" class="choice learn vote">
        <svg viewBox="0 0 24 24" aria-hidden="true"><path d="M12 3l2.6 5.6 6.1.7-4.5 4.2 1.2 6L12 16.5 6.6 19.5l1.2-6L3.3 9.3l6.1-.7z" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linejoin="round"/></svg>
        <span><b>Vote on the demo presets</b><small>Test version: listen to the demo one phrase at a time and give each preset 1 to 10 stars. Under 5, five other presets are offered; a 10 can be moved to the start of the demo.</small></span></button>
`);
html = html.replace(/<title>([^<]*)<\/title>/, (m, t) => `<title>${t} - demo vote (test)</title>`);
fs.writeFileSync(path.join(OUT, 'index.html'), crlf ? html.replace(/\n/g, '\r\n') : html);

fs.writeFileSync(path.join(OUT, 'VOTE-TEST.md'), `# OktoWave - demo vote (test version)

A test copy of the web app to sort the presets of the demo (it is not a release). Open it, click **Vote on the demo presets** (or **★ VOTE** in the header), and listen: the demo plays one phrase of Beethoven's
*Appassionata* per preset (30 parts, 8 beats each). When a phrase ends, rate the preset 1 to 10 stars (click, or press 1 to 9 and 0 for 10).

- 8 stars or more (and 5, 6, 7): nothing changes.
- 10 stars: the page offers to move the preset to the start of the demo and asks at which position.
- under 5 stars: five other presets of the factory list are offered, each one can be heard on the same phrase; take the right one ("5 more" gives five others).
- at the end: a summary, then **the whole demo is played again** with the new list; press **Accept** if it is right.
- **Send report** posts the list of presets of every part to the feedback Google Form; **Copy** and **Download** keep the same text.

Your progress is kept in this browser (Continue at part N). Made by tools/make_vote_build.js from the OktoWave sources.
`);
const n = fs.readdirSync(OUT, { recursive: true }).length;
console.log(`vote build: ${OUT} (${n} entries, ${Object.keys(trim).length} trims)`);
