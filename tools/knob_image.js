// metal tinted towards pink, its white dot removed) for the plug-in, which has no PNG decoder: web/img/bouton_cuivre_rose.png (156 x 156, a disc of radius 74.3 px in the
// middle, a transparent edge) as rows of 0xAARRGGBB, not premultiplied, in vst/src/generated/knob_image.h (vst/src/editor.cpp resamples it to each knob's size).
//   node tools/knob_image.js
'use strict';
const fs = require('fs');
const path = require('path');
const { decodePng } = require('../tests/web/png.js');
const root = path.join(__dirname, '..');
const img = decodePng(fs.readFileSync(path.join(root, 'web', 'img', 'bouton_cuivre_rose.png')));
if (img.channels !== 4) throw new Error('the knob picture needs an alpha channel');
const n = img.width * img.height, words = [];
for (let i = 0; i < n; i++) {
  const r = img.data[4 * i], g = img.data[4 * i + 1], b = img.data[4 * i + 2], a = img.data[4 * i + 3];
  words.push('0x' + ((a << 24 | r << 16 | g << 8 | b) >>> 0).toString(16).padStart(8, '0'));
}
let h = '// GENERATED by tools/knob_image.js from web/img/bouton_cuivre_rose.png: do not edit.\n#pragma once\n#include <cstdint>\nnamespace ws {\n';
h += `inline constexpr int kKnobImgW = ${img.width}, kKnobImgH = ${img.height};\n`;
h += 'inline constexpr float kKnobImgDiscR = 74.3f;   // the knob disc\'s radius in the picture, px\n';
h += 'inline constexpr uint32_t kKnobImg[] = {\n';
for (let i = 0; i < n; i += 12) h += '  ' + words.slice(i, i + 12).join(', ') + ',\n';
h += '};\n}  // namespace ws\n';
fs.writeFileSync(path.join(root, 'vst', 'src', 'generated', 'knob_image.h'), h);
console.log(`vst/src/generated/knob_image.h: ${img.width} x ${img.height}`);
