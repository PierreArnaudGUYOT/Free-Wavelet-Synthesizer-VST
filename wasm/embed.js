// WebAssembly prototype: writes web/js/engine_wasm_data.js, the two builds of the engine (wasm/out/engine_simd.wasm, engine_scalar.wasm) in base64, so that the web app
// loads them from file:// (a fetch of a .wasm file is refused there). The page picks the SIMD one when the browser validates it, else the scalar one.
//   node wasm/embed.js   (wasm/build.sh runs it)
'use strict';
const fs = require('fs'), path = require('path');
const out = path.join(__dirname, 'out');
const b64 = f => fs.readFileSync(path.join(out, f)).toString('base64');
const src = '// Copyright (C) 2026 Pierre Arnaud GUYOT (OktoPierre)\n// SPDX-License-Identifier: GPL-3.0-or-later\n' +
  '// GENERATED by wasm/embed.js from wasm/out/*.wasm (the C++ engine, vst/src/dsp.h, built by wasm/build.sh): do not edit.\n' +
  `var WS_WASM = { simd: '${b64('engine_simd.wasm')}',\n  scalar: '${b64('engine_scalar.wasm')}' };\n` +
  "if (typeof module !== 'undefined') module.exports = WS_WASM;\n";
const dst = path.join(__dirname, '..', 'web', 'js', 'engine_wasm_data.js');
fs.writeFileSync(dst, src);
console.log(`${path.relative(process.cwd(), dst)}: ${src.length} bytes`);
